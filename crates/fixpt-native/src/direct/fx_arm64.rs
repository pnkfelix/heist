//! What the compiler written in FX-26 for arm64 (`native-direct-arm64.fx`
//! and the files beside it, `procedure` step for step) is told of the
//! machine, generated; and the Rust compiler's pieces by name, its oracle
//! piece by piece (`fixpt-fx26/tests/native_direct_arm64*.rs`), as
//! `x64.rs`'s are for x86_64.

use super::*;

/// The native convention on arm64 as the compiler written in FX-26 knows
/// it (`native-direct-arm64-layout.fx`): its registers, then all that
/// x86_64's says too (`x64::fx26_direct_layout_of`), by the same names.
/// Generated so (`tests/layout.rs` in `fixpt-fx26`).
pub fn fx26_direct_arm64_module() -> String {
    layout().0
}

/// The signature of [`fx26_direct_arm64_module`]'s module, as a module file
/// of types (`native-direct-arm64-layout-types.fx`).
pub fn fx26_direct_arm64_module_sig() -> String {
    layout().1
}

fn layout() -> (String, String) {
    let regs = [
        ("d-result", RESULT),
        ("d-clo", CLO),
        ("d-st", ST),
        ("d-fuel", FUEL),
        ("d-limit", LIMIT),
        ("d-frame", FRAME),
        ("d-link", LINK),
        ("d-delta", DELTA),
        ("d-sp", SP),
        ("d-xzr", XZR),
        ("d-x9", X9),
        ("d-x11", X11),
        ("d-x12", X12),
        ("d-x13", X13),
        ("d-x14", X14),
        ("d-x15", X15),
        ("d-x16", X16),
        ("d-x17", X17),
    ]
    .map(|(name, r)| (name, r as i64));
    x64::fx26_direct_layout_of(
        &[
            "Generated by `fixpt_native::direct::fx26_direct_arm64_module` from the native",
            "convention on arm64 (`direct.rs`); `FIXPT_BLESS=1 cargo test -p fixpt-fx26",
            "--test layout` rewrites it. A module file, which the conductor loads (`TODO.md` §68).",
        ],
        &regs,
        &["Generated by `fixpt_native::direct::fx26_direct_arm64_module_sig`, beside", "`native-direct-arm64-layout.fx`: its module's signature. A module file of no state."],
        "native-direct-arm64-layout-sig",
    )
}

/// The Rust compiler's pieces by name, for the compiler written in FX-26 to
/// be checked against piece by piece (`fixpt-fx26/tests/native_direct_arm64*.rs`):
/// the instructions `name` emits given `args`, as bytes, with the call-outs
/// it numbers from 0 (`fx::callout_code`); or none for a name it does not
/// know.
#[doc(hidden)]
pub fn oracle(name: &str, args: &[i64]) -> Option<(Vec<u8>, Vec<i64>)> {
    oracle_asm::oracle(name, args).or_else(|| oracle_raw::oracle(name, args)).or_else(|| oracle_flat::oracle(name, args)).or_else(|| oracle_prims::oracle(name, args))
}

