//! Compiles the stencils (`stencils/cellular.rs`) with the installed nightly,
//! once per optimisation level, reads the objects, and writes their machine
//! code out as tables for `src/stencil.rs`.
//!
//! What it insists on, so that a stencil placed by copying runs correctly:
//! no relocations at all, and no branch that leaves the stencil. Anything
//! else fails the build, with the offending stencil named.
//!
//! No nightly, no stencils: the build carries on without them, and says so.
//! Likewise on a target that is neither arm64 nor x86_64 Linux.
//!
//! The object is Mach-O on macOS and ELF on Linux; each has a small reader.
//! An arm64 branch is checked in the machine code, its instructions all
//! four bytes; an x86_64 one in the assembly LLVM writes beside the
//! object, whose branches name their targets.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::{env, fs};

use fixpt_engine::cellular::Trap;
use fixpt_heap::layout::cellular::{KIND, PRIMITIVES, ROUTINES, WORD_CELL0, WORD_ENTRY};
use fixpt_heap::Value;
use fixpt_heap::value::{TAG_BLOBLET, TAG_MASK, TAG_PAIR, TAG_TRAILER};

/// The optimisation levels the stencils are compiled at.
const OPT_LEVELS: &[&str] = &["0", "1", "2", "3", "s"];

/// A routine's name as a Rust identifier.
fn ident(name: &str) -> String {
    match name {
        "+" => "add".into(),
        "-" => "sub".into(),
        "<" => "less".into(),
        "field@" => "field_ref".into(),
        "field!" => "field_set".into(),
        "0branch" => "zbranch".into(),
        // `local!` and the like: a Rust identifier has no `!`.
        n => n.replace('!', "_set").replace('-', "_"),
    }
}

fn consts() -> String {
    let mut s = String::from("// Generated by build.rs from the layout table.\n");
    let mut c = |name: &str, v: u64| writeln!(s, "pub const {name}: u64 = {v:#x};").unwrap();
    c("TAG_MASK", TAG_MASK);
    c("TAG_PAIR", TAG_PAIR);
    c("TAG_BLOBLET", TAG_BLOBLET);
    c("TAG_TRAILER", TAG_TRAILER);
    c("FALSE", Value::FALSE.raw());
    c("TRUE", Value::TRUE.raw());
    c("PROMPT_MARK", fixpt_engine::cellular::PROMPT_MARK.raw());
    c("MARK_MARK", fixpt_engine::cellular::MARK_MARK.raw());
    c("WORD_KIND", KIND as u64);
    c("CLOSURE_KIND", fixpt_heap::layout::kind("cellular-closure") as u64);
    c("CLOSURE_WORD", fixpt_heap::layout::cellular::CLOSURE_WORD as u64);
    c("CLOSURE_FREE0", fixpt_heap::layout::cellular::CLOSURE_FREE0 as u64);
    c("WORD_ENTRY", WORD_ENTRY as u64);
    c("WORD_CELL0", WORD_CELL0 as u64);
    c("PRIMITIVES", PRIMITIVES as u64);
    for (i, (name, _)) in ROUTINES.iter().enumerate() {
        c(&format!("R_{}", ident(name).to_uppercase()), i as u64);
    }
    let r = "+";
    for (name, t) in [
        ("TYPE", Trap::Type { routine: r }),
        ("OVERFLOW", Trap::Overflow { routine: r }),
        ("UNDERFLOW", Trap::Underflow { routine: r }),
        ("FIELD", Trap::Field { routine: r }),
        ("NO_ROUTINE", Trap::NoRoutine(0)),
        ("NOT_A_WORD", Trap::NotAWord),
        ("OUT_OF_FUEL", Trap::OutOfFuel),
        ("STACK_OVERFLOW", Trap::StackOverflow),
        ("TOO_DEEP", Trap::TooDeep),
    ] {
        c(&format!("TRAP_{name}"), t.code().0);
    }
    s
}

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=stencils/cellular.rs");
    println!("cargo:rerun-if-changed=src/state.rs");
    fs::copy("stencils/cellular.rs", out.join("cellular.rs")).unwrap();
    fs::copy("src/state.rs", out.join("state.rs")).unwrap();
    fs::write(out.join("consts.rs"), consts()).unwrap();

    let mut table = String::from("// Generated by build.rs: the stencils' machine code.\npub static STENCIL_SETS: &[StencilSet] = &[\n");
    let mut listing = String::new();
    let target = env::var("TARGET").unwrap();
    let format = match target.as_str() {
        "aarch64-apple-darwin" => Some(Format::MachO),
        t if t.starts_with("aarch64-") && t.contains("-linux-") => Some(Format::Elf),
        t if t.starts_with("x86_64-") && t.contains("-linux-") => Some(Format::ElfX64),
        _ => None,
    };
    let Some(format) = format else {
        println!("cargo:warning=no stencils: they are arm64 or x86_64 Linux code, and the target is {target}");
        fs::write(out.join("stencils.rs"), "pub static STENCIL_SETS: &[StencilSet] = &[\n];\n").unwrap();
        fs::write(out.join("stencils.txt"), "").unwrap();
        return;
    };
    for opt in OPT_LEVELS {
        let obj = out.join(format!("cellular-O{opt}.o"));
        let asm = matches!(format, Format::ElfX64).then(|| out.join(format!("cellular-O{opt}.s")));
        match compile(&out, &target, opt, &obj, asm.as_deref()) {
            Ok(()) => {}
            // No nightly, or none for this target: build without stencils,
            // and say so.
            Err(Compile::NoNightly(e)) => {
                println!("cargo:warning=no stencils: {e}");
                table = String::from("pub static STENCIL_SETS: &[StencilSet] = &[\n");
                break;
            }
            // A nightly that rejects the stencils: a bug here, not a missing
            // tool, so the build stops and says what.
            Err(Compile::Failed(e)) => panic!("the stencils do not compile at -O{opt}:\n{e}"),
        }
        let bytes = fs::read(&obj).unwrap();
        let stencils = match format {
            Format::MachO => read_stencils(&bytes),
            Format::Elf => read_stencils_elf(&bytes, 183, check_branches),
            Format::ElfX64 => {
                let text = fs::read_to_string(asm.as_ref().unwrap()).unwrap();
                read_stencils_elf(&bytes, 62, |_, _| Ok(())).and_then(|s| {
                    for (name, _) in &s {
                        check_branches_x64(name, &text)?;
                    }
                    Ok(s)
                })
            }
        };
        let stencils = stencils.unwrap_or_else(|e| panic!("stencils at -O{opt}: {e}"));
        writeln!(table, "  StencilSet {{ opt: {opt:?}, stencils: &[").unwrap();
        writeln!(listing, "-C opt-level={opt}").unwrap();
        for (name, code) in &stencils {
            writeln!(table, "    ({name:?}, &{code:?}),").unwrap();
            writeln!(listing, "  {name:<16} {:>4} bytes", code.len()).unwrap();
        }
        writeln!(table, "  ]}},").unwrap();
    }
    table.push_str("];\n");
    fs::write(out.join("stencils.rs"), table).unwrap();
    fs::write(out.join("stencils.txt"), listing).unwrap();
}

enum Format {
    MachO,
    Elf,
    ElfX64,
}

enum Compile {
    NoNightly(String),
    Failed(String),
}

/// The stencils compiled at `-C opt-level=opt` to `obj`, and to `asm` too
/// if it is given, the assembly for the same code.
fn compile(dir: &Path, target: &str, opt: &str, obj: &Path, asm: Option<&Path>) -> Result<(), Compile> {
    let emit = match asm {
        Some(asm) => format!("obj={},asm={}", obj.display(), asm.display()),
        None => format!("obj={}", obj.display()),
    };
    let out = Command::new("rustup")
        .args(["run", "nightly", "rustc", "--edition", "2024", "--crate-type", "lib", "--emit", &emit])
        .args(["--target", target, "-C", &format!("opt-level={opt}")])
        // On ELF each function would otherwise get a section of its own;
        // one `.text` keeps the reader as simple as the Mach-O one.
        .args(["-Z", "function-sections=no"])
        .args(["-C", "panic=abort", "-C", "debuginfo=0", "-C", "llvm-args=-enable-machine-outliner=never"])
        // Only the optimisation level varies: the checks a debug build adds
        // (overflow, and null and alignment on every dereference) call into
        // `core`, which a stencil cannot reach, so they are off at every level.
        .args(["-C", "debug-assertions=off", "-C", "overflow-checks=off"])
        .arg(dir.join("cellular.rs"))
        .output()
        .map_err(|e| Compile::NoNightly(format!("cannot run `rustup run nightly rustc`: {e}")))?;
    if !out.status.success() {
        let err = String::from_utf8_lossy(&out.stderr).into_owned();
        // rustup's own complaint, when no nightly is installed; or rustc's,
        // when the nightly has no standard library for the target (building
        // for another machine than this one).
        if (err.contains("toolchain 'nightly") && err.contains("not installed"))
            || (err.contains("E0463") && err.contains("target may not be installed"))
        {
            return Err(Compile::NoNightly(err));
        }
        return Err(Compile::Failed(err));
    }
    Ok(())
}

// ----------------------------------------------------- a small Mach-O reader

fn u32le(b: &[u8], o: usize) -> u32 {
    u32::from_le_bytes(b[o..o + 4].try_into().unwrap())
}
fn u64le(b: &[u8], o: usize) -> u64 {
    u64::from_le_bytes(b[o..o + 8].try_into().unwrap())
}
fn cstr(b: &[u8], o: usize) -> String {
    let e = b[o..].iter().position(|&c| c == 0).unwrap();
    String::from_utf8_lossy(&b[o..o + e]).into_owned()
}
fn fixed(b: &[u8]) -> String {
    let e = b.iter().position(|&c| c == 0).unwrap_or(b.len());
    String::from_utf8_lossy(&b[..e]).into_owned()
}

struct Sect {
    name: String,
    addr: u64,
    size: u64,
    off: u32,
    nreloc: u32,
}

/// Every `st_` function in `__text`, as `(name, code)`, checked.
fn read_stencils(b: &[u8]) -> Result<Vec<(String, Vec<u8>)>, String> {
    if u32le(b, 0) != 0xfeed_facf || u32le(b, 4) != 0x0100_000c || u32le(b, 12) != 1 {
        return Err("not an arm64 Mach-O object".into());
    }
    let ncmds = u32le(b, 16) as usize;
    let mut p = 32;
    let mut sects = Vec::new();
    let mut syms = Vec::new();
    for _ in 0..ncmds {
        let (cmd, size) = (u32le(b, p), u32le(b, p + 4) as usize);
        match cmd {
            0x19 => {
                for i in 0..u32le(b, p + 64) as usize {
                    let s = p + 72 + i * 80;
                    sects.push(Sect {
                        name: format!("{},{}", fixed(&b[s + 16..s + 32]), fixed(&b[s..s + 16])),
                        addr: u64le(b, s + 32),
                        size: u64le(b, s + 40),
                        off: u32le(b, s + 48),
                        nreloc: u32le(b, s + 60),
                    });
                }
            }
            0x2 => {
                let (symoff, nsyms, stroff) = (u32le(b, p + 8) as usize, u32le(b, p + 12) as usize, u32le(b, p + 16) as usize);
                for i in 0..nsyms {
                    let e = symoff + i * 16;
                    syms.push((cstr(b, stroff + u32le(b, e) as usize), b[e + 5], u64le(b, e + 8)));
                }
            }
            _ => {}
        }
        p += size;
    }
    let ti = sects.iter().position(|s| s.name == "__TEXT,__text").ok_or("no __text")?;
    let text = &sects[ti];
    if text.nreloc != 0 {
        return Err(format!("__text has {} relocations; a stencil must have none", text.nreloc));
    }
    for s in &sects {
        if s.name != "__TEXT,__text" && s.nreloc != 0 {
            return Err(format!("{} has relocations", s.name));
        }
    }
    let mut starts: Vec<(u64, &str)> =
        syms.iter().filter(|s| s.1 as usize == ti + 1).map(|s| (s.2, s.0.as_str())).collect();
    starts.sort();
    let mut out = Vec::new();
    for (i, &(start, name)) in starts.iter().enumerate() {
        let end = starts.get(i + 1).map(|x| x.0).unwrap_or(text.addr + text.size);
        // Anything else (the panic handler) is unreachable from a stencil:
        // there are no relocations, and every stencil's branches stay in it.
        let Some(name) = name.strip_prefix("_st_") else {
            continue;
        };
        let code = b[text.off as usize + start as usize..text.off as usize + end as usize].to_vec();
        check_branches(name, &code)?;
        out.push((name.to_string(), code));
    }
    Ok(out)
}

// ------------------------------------------------------- a small ELF reader

fn u16le(b: &[u8], o: usize) -> u16 {
    u16::from_le_bytes(b[o..o + 2].try_into().unwrap())
}

/// As [`read_stencils`], for an ELF relocatable object of machine `em`
/// (`EM_AARCH64`, 183, or `EM_X86_64`, 62), each stencil's branches checked
/// by `check`.
fn read_stencils_elf(b: &[u8], em: u16, check: fn(&str, &[u8]) -> Result<(), String>) -> Result<Vec<(String, Vec<u8>)>, String> {
    // 64-bit, little-endian, relocatable, of the machine.
    if b.get(..4) != Some(b"\x7fELF") || b[4] != 2 || b[5] != 1 || u16le(b, 16) != 1 || u16le(b, 18) != em {
        return Err(format!("not an ELF object for machine {em}"));
    }
    let (shoff, shentsize, shnum, shstrndx) =
        (u64le(b, 40) as usize, u16le(b, 58) as usize, u16le(b, 60) as usize, u16le(b, 62) as usize);
    // (name, type, offset, size, link, info)
    let sh = |i: usize| {
        let s = shoff + i * shentsize;
        (u32le(b, s) as usize, u32le(b, s + 4), u64le(b, s + 24) as usize, u64le(b, s + 32) as usize, u32le(b, s + 40) as usize, u32le(b, s + 44) as usize)
    };
    let strtab_off = sh(shstrndx).2;
    let name = |i: usize| cstr(b, strtab_off + sh(i).0);
    let ti = (0..shnum).find(|&i| name(i) == ".text").ok_or("no .text")?;
    // SHT_RELA, SHT_REL: none may apply to code.
    for i in 0..shnum {
        let (_, ty, _, size, _, info) = sh(i);
        if (ty == 4 || ty == 9) && size != 0 && name(info).starts_with(".text") {
            return Err(format!("{} has relocations; a stencil must have none", name(i)));
        }
    }
    let si = (0..shnum).find(|&i| sh(i).1 == 2).ok_or("no symbol table")?; // SHT_SYMTAB
    let (_, _, symoff, symsize, strndx, _) = sh(si);
    let symstr = sh(strndx).2;
    let text = sh(ti).2;
    let mut out = Vec::new();
    for e in (symoff..symoff + symsize).step_by(24) {
        // Anything else (the panic handler) is unreachable from a stencil,
        // as in the Mach-O reader.
        let Some(name) = cstr(b, symstr + u32le(b, e) as usize).strip_prefix("st_").map(str::to_string) else {
            continue;
        };
        if u16le(b, e + 6) as usize != ti {
            return Err(format!("st_{name} is not in .text"));
        }
        let (value, size) = (u64le(b, e + 8) as usize, u64le(b, e + 16) as usize);
        let code = b[text + value..text + value + size].to_vec();
        check(&name, &code)?;
        out.push((value, name, code));
    }
    // In address order, as the Mach-O reader gives them.
    out.sort();
    Ok(out.into_iter().map(|(_, name, code)| (name, code)).collect())
}

/// Every direct branch in a stencil must land inside it.
fn check_branches(name: &str, code: &[u8]) -> Result<(), String> {
    let n = code.len() as i64 / 4;
    for i in 0..n {
        let w = u32le(code, 4 * i as usize);
        let sext = |v: u32, bits: u32| ((v << (32 - bits)) as i32 >> (32 - bits)) as i64;
        let target = if w & 0x7C00_0000 == 0x1400_0000 {
            Some(sext(w & 0x03FF_FFFF, 26)) // b, bl
        } else if w & 0xFF00_0010 == 0x5400_0000 || w & 0x7E00_0000 == 0x3400_0000 {
            Some(sext((w >> 5) & 0x7FFFF, 19)) // b.cond, cbz, cbnz
        } else if w & 0x7E00_0000 == 0x3600_0000 {
            Some(sext((w >> 5) & 0x3FFF, 14)) // tbz, tbnz
        } else {
            None
        };
        if let Some(d) = target
            && !(0..n).contains(&(i + d))
        {
            return Err(format!("st_{name}: the branch at +{:#x} leaves the stencil", 4 * i));
        }
    }
    Ok(())
}

/// As [`check_branches`], for x86_64, in the assembly LLVM wrote for the
/// object: every jump or call in `st_name` either indirect (`*%reg`,
/// `*mem`: the routine table, the call-out) or to a label inside it.
fn check_branches_x64(name: &str, asm: &str) -> Result<(), String> {
    let head = format!("st_{name}:");
    let mut lines = asm.lines().map(|l| l.split('#').next().unwrap_or("").trim()).skip_while(|l| *l != head).skip(1);
    // Its lines, to where the next function's begin, or its own end label.
    let body: Vec<&str> = lines.by_ref().take_while(|l| !l.starts_with(".Lfunc_end") && !l.starts_with(".type")).collect();
    if body.is_empty() {
        return Err(format!("st_{name} is not in the assembly"));
    }
    let labels: Vec<&str> = body.iter().filter_map(|l| l.strip_suffix(':')).collect();
    for l in &body {
        let mut words = l.split_whitespace();
        let Some(op) = words.next() else { continue };
        if !(op.starts_with('j') || op.starts_with("call")) {
            continue;
        }
        let target = words.collect::<Vec<_>>().join(" ");
        if !target.starts_with('*') && !labels.contains(&target.as_str()) {
            return Err(format!("st_{name}: `{l}` leaves the stencil"));
        }
    }
    Ok(())
}
